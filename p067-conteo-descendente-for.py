# Imprime numeros de manera descendente de 100 1 en decrementos de 1 usando for

print('\033[2J\033[H', end='')
print('Imprime numeros de manera descendente de 100 1 en decrementos de 1 usando for\n')

for i in range(100, 0, -1):
    print(i)

print('\n Proceso Terminado')